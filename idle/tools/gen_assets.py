#!/usr/bin/env python3
"""Generates every image the game uses and the atlas index `js/atlas.js`.

    python3 idle/tools/gen_assets.py

Needs Python 3 with numpy and Pillow. Output is deterministic (fixed seeds), so re-running it
only changes files whose drawing code changed.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from PIL import Image  # noqa: E402

import backgrounds  # noqa: E402
import icons  # noqa: E402
import sprites  # noqa: E402
import ui  # noqa: E402

ROOT = os.path.dirname(HERE)
ASSETS = os.path.join(ROOT, 'assets')


def pack(images, max_w=1024, pad=1):
    """Shelf packer: tallest first. Returns (atlas image, {name: [x, y, w, h]})."""
    order = sorted(images, key=lambda n: (-images[n].height, -images[n].width, n))
    x = y = shelf = 0
    pos = {}
    width = 0
    for n in order:
        im = images[n]
        if x + im.width + pad > max_w:
            x = 0
            y += shelf + pad
            shelf = 0
        pos[n] = [x, y, im.width, im.height]
        x += im.width + pad
        width = max(width, x)
        shelf = max(shelf, im.height)
    atlas = Image.new('RGBA', (width, y + shelf), (0, 0, 0, 0))
    for n, (px, py, _, _) in pos.items():
        atlas.alpha_composite(images[n], (px, py))
    return atlas, pos


def grid(images, cell=32, cols=16):
    names = sorted(images)
    rows = (len(names) + cols - 1) // cols
    atlas = Image.new('RGBA', (cols * cell, rows * cell), (0, 0, 0, 0))
    pos = {}
    for i, n in enumerate(names):
        x, y = (i % cols) * cell, (i // cols) * cell
        atlas.alpha_composite(images[n], (x, y))
        pos[n] = [x, y]
    return atlas, pos


def main():
    os.makedirs(os.path.join(ASSETS, 'bg'), exist_ok=True)
    os.makedirs(os.path.join(ASSETS, 'ui'), exist_ok=True)

    spr = sprites.catalogue()
    satlas, spos = pack(spr)
    satlas.save(os.path.join(ASSETS, 'sprites.png'), optimize=True)

    ico = icons.catalogue()
    iatlas, ipos = grid(ico)
    iatlas.save(os.path.join(ASSETS, 'icons.png'), optimize=True)

    bgs = backgrounds.catalogue()
    for n, im in bgs.items():
        im.save(os.path.join(ASSETS, 'bg', n + '.png'), optimize=True)

    uis = ui.catalogue()
    for n, im in uis.items():
        im.save(os.path.join(ASSETS, 'ui', n + '.png'), optimize=True)

    index = dict(
        sprites=dict(size=list(satlas.size), map=spos),
        icons=dict(size=list(iatlas.size), cell=32, map=ipos),
        backgrounds=sorted(bgs),
    )
    js = '// Generated by tools/gen_assets.py — do not edit.\nconst ATLAS = ' + json.dumps(index, separators=(',', ':'), sort_keys=True) + ';\n'
    with open(os.path.join(ROOT, 'js', 'atlas.js'), 'w') as f:
        f.write(js)
    total = sum(os.path.getsize(os.path.join(dp, f)) for dp, _, fs in os.walk(ASSETS) for f in fs)
    print(f'{len(spr)} sprites, {len(ico)} icons, {len(bgs)} backgrounds, {len(uis)} ui textures; {total // 1024} KiB')


if __name__ == '__main__':
    main()
